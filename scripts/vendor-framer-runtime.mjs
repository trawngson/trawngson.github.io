const output = join(root, "assets/framer")
const siteBase =
  "https://framerusercontent.com/sites/5Kx2XLMGy1pa7UdUQDRO4o/"

// Observed while rendering every published route. The recursive import scan
// below also follows any same-site .mjs dependency referenced by these files.
